-- Run this in Supabase Dashboard > SQL Editor.
-- These tables support per-user save files and leaderboard submissions.
-- Keep Row Level Security enabled. Never place a service_role key in browser code.

create table if not exists public.game_saves (
  user_id uuid primary key references auth.users(id) on delete cascade,
  save_data jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

alter table public.game_saves enable row level security;

drop policy if exists "Players can read their own game save" on public.game_saves;
create policy "Players can read their own game save"
  on public.game_saves for select
  to authenticated
  using (auth.uid() = user_id);

drop policy if exists "Players can create their own game save" on public.game_saves;
create policy "Players can create their own game save"
  on public.game_saves for insert
  to authenticated
  with check (auth.uid() = user_id);

drop policy if exists "Players can update their own game save" on public.game_saves;
create policy "Players can update their own game save"
  on public.game_saves for update
  to authenticated
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

create table if not exists public.leaderboard (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  player_name text not null default 'Wizard',
  house text not null default 'Gryffindor'
    check (house in ('Gryffindor', 'Ravenclaw', 'Hufflepuff', 'Slytherin')),
  score integer not null default 0 check (score >= 0),
  victory boolean not null default false,
  created_at timestamptz not null default now()
);

create index if not exists leaderboard_score_idx
  on public.leaderboard (score desc, created_at asc);

alter table public.leaderboard enable row level security;

drop policy if exists "Anyone can view leaderboard" on public.leaderboard;
create policy "Anyone can view leaderboard"
  on public.leaderboard for select
  to anon, authenticated
  using (true);

drop policy if exists "Authenticated players can submit their own score" on public.leaderboard;
create policy "Authenticated players can submit their own score"
  on public.leaderboard for insert
  to authenticated
  with check (auth.uid() = user_id);

